static inline uint16_t align2(uint32_t v)
{
    return (uint16_t)((v + 1u) & ~1u);
}

const uint8_t *nid_overlay_glyph(char c)
{
    unsigned char uc = (unsigned char)c;
    if (uc < OV_FIRST_CHAR || uc > OV_LAST_CHAR) {
        uc = '?';
    }
    return s_font[uc - OV_FIRST_CHAR];
}

uint8_t nid_overlay_auto_scale(uint16_t frame_h)
{
    /* Hauteur des capitales ≈ 3,2 % de la hauteur de l'image : lisible en 1080p
     * sans masquer une part importante du champ. */
    uint32_t s = ((uint32_t)frame_h + 120u) / 240u;
    if (s < 1) {
        s = 1;
    }
    if (s > 8) {
        s = 8;
    }
    return (uint8_t)s;
}

bool nid_overlay_init(nid_overlay_t *ov, uint16_t frame_w, uint16_t frame_h,
                      uint8_t scale, bool bottom, bool full_range)
{
    if (ov == NULL || frame_w < 16 || frame_h < 16 || (frame_w & 1) || (frame_h & 1)) {
        return false;
    }
    uint8_t *keep = ov->tpl;
    size_t keep_cap = ov->tpl_cap;
    memset(ov, 0, sizeof(*ov));
    ov->tpl = keep;
    ov->tpl_cap = keep_cap;
    ov->frame_w = frame_w;
    ov->frame_h = frame_h;
    ov->scale_max = scale ? scale : nid_overlay_auto_scale(frame_h);
    ov->bottom = bottom;
    ov->y_fg = full_range ? 255 : 235;
    ov->y_bg = full_range ? 0 : 16;
    return true;
}

void nid_overlay_deinit(nid_overlay_t *ov)
{
    if (ov == NULL) {
        return;
    }
    if (ov->tpl) {
        OV_FREE(ov->tpl);
    }
    memset(ov, 0, sizeof(*ov));
}

/* Luminance du pixel (x, r) du cadre ; r = ligne de glyphe ou OV_BLANK_ROW. */
static uint8_t ov_pixel(const nid_overlay_t *ov, size_t nchars, uint32_t r, uint32_t x)
{
    const uint32_t s = ov->scale;
    const uint32_t pad = s;
    const uint32_t cell = NID_OVERLAY_CELL_W * s;
    const uint32_t text_w = (uint32_t)nchars * cell - s;

    if (r == OV_BLANK_ROW || x < pad || x - pad >= text_w) {
        return ov->y_bg;
    }
    uint32_t tx = x - pad;
    uint32_t ci = tx / cell;
    uint32_t cx = (tx % cell) / s;
    if (ci >= nchars || cx >= 5) {
        return ov->y_bg;
    }
    uint8_t bits = nid_overlay_glyph(ov->text[ci])[r];
    return ((bits >> (4 - cx)) & 1u) ? ov->y_fg : ov->y_bg;
}

bool nid_overlay_set_text(nid_overlay_t *ov, const char *text)
{
    if (ov == NULL || ov->frame_w == 0) {
        return false;
    }
    char tmp[NID_OVERLAY_MAX_CHARS + 1];
    size_t n = 0;
    if (text) {
        for (; text[n] != '\0' && n < NID_OVERLAY_MAX_CHARS; n++) {
            unsigned char c = (unsigned char)text[n];
            tmp[n] = (c < OV_FIRST_CHAR || c > OV_LAST_CHAR) ? '?' : (char)c;
        }
    }
    tmp[n] = '\0';
    if (ov->box_w != 0 && strcmp(tmp, ov->text) == 0) {
        return true;
    }
    if (n == 0) {
        ov->text[0] = '\0';
        ov->box_w = 0;
        ov->box_h = 0;
        return true;
    }

    /* Facteur effectif : le cadre doit tenir dans la largeur avec ses marges. */
    uint32_t s = ov->scale_max ? ov->scale_max : 1;
    for (;;) {
        uint32_t margin = align2(2 * s);
        uint32_t box_w = align2((uint32_t)n * NID_OVERLAY_CELL_W * s - s + 2 * s);
        uint32_t box_h = align2(NID_OVERLAY_CELL_H * s + 2 * s);
        if ((box_w + 2 * margin <= ov->frame_w && box_h + 2 * margin <= ov->frame_h) || s == 1) {
            break;
        }
        s--;
    }
    ov->scale = (uint8_t)s;
    uint32_t margin = align2(2 * s);
    /* À l'échelle 1, tronque le texte s'il ne tient toujours pas. */
    uint32_t avail_w = (ov->frame_w > 2 * margin) ? ov->frame_w - 2 * margin : ov->frame_w;
    while (n > 0 && align2((uint32_t)n * NID_OVERLAY_CELL_W * s + s) > avail_w) {
        n--;
    }
    tmp[n] = '\0';
    memcpy(ov->text, tmp, n + 1);

    if (n == 0) {
        ov->box_w = 0;
        ov->box_h = 0;
        return true;
    }

    uint32_t box_w = align2((uint32_t)n * NID_OVERLAY_CELL_W * s - s + 2 * s);
    uint32_t box_h = align2(NID_OVERLAY_CELL_H * s + 2 * s);
    if (box_h + 2 * margin > ov->frame_h) {
        margin = 0;
    }
    if (box_w > ov->frame_w || box_h > ov->frame_h) {
        ov->box_w = 0;
        ov->box_h = 0;
        return true;
    }
    size_t row_bytes = (size_t)box_w / 2 * 3;
    size_t need = (size_t)(NID_OVERLAY_CELL_H + 1) * row_bytes;
    if (ov->tpl_cap < need) {
        uint8_t *p = OV_ALLOC(need);
        if (p == NULL) {
            ov->box_w = 0;
            ov->box_h = 0;
            return false;
        }
        if (ov->tpl) {
            OV_FREE(ov->tpl);
        }
        ov->tpl = p;
        ov->tpl_cap = need;
    }
    ov->box_w = (uint16_t)box_w;
    ov->box_h = (uint16_t)box_h;
    ov->box_x = (uint16_t)margin;
    ov->box_y = (uint16_t)(ov->bottom ? (ov->frame_h - box_h - margin) : margin);

    for (uint32_t r = 0; r <= OV_BLANK_ROW; r++) {
        uint8_t *row = ov->tpl + r * row_bytes;
        for (uint32_t x = 0; x < box_w; x += 2) {
            uint8_t *g = row + (x / 2) * 3;
            g[0] = OV_CHROMA_GREY;
            g[1] = ov_pixel(ov, n, r, x);
            g[2] = ov_pixel(ov, n, r, x + 1);
        }
    }
    return true;
}

void nid_overlay_draw(const nid_overlay_t *ov, uint8_t *frame)
{
    if (ov == NULL || frame == NULL || ov->box_w == 0 || ov->tpl == NULL) {
        return;
    }
    const size_t stride = (size_t)ov->frame_w / 2 * 3;
    const size_t row_bytes = (size_t)ov->box_w / 2 * 3;
    const uint32_t s = ov->scale;
    const uint32_t pad = s;
    uint8_t *dst = frame + (size_t)ov->box_y * stride + (size_t)ov->box_x / 2 * 3;
    for (uint32_t y = 0; y < ov->box_h; y++, dst += stride) {
        uint32_t r = OV_BLANK_ROW;
        if (y >= pad && y < pad + NID_OVERLAY_CELL_H * s) {
            r = (y - pad) / s;
        }
        memcpy(dst, ov->tpl + r * row_bytes, row_bytes);
    }
}

bool nid_overlay_dirty_range(const nid_overlay_t *ov, size_t *offset, size_t *len)
{
    if (ov == NULL || ov->box_w == 0) {
        return false;
    }
    const size_t stride = (size_t)ov->frame_w / 2 * 3;
    *offset = (size_t)ov->box_y * stride;
    *len = (size_t)ov->box_h * stride;
    return true;
}
